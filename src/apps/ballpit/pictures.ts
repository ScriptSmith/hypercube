const n = (v: number) => String(Math.round(v * 100) / 100);

const c = (x: number, y: number, r: number, f = I) =>
  `<circle cx="${n(x)}" cy="${n(y)}" r="${n(r)}" fill="${f}"/>`;
const ring = (x: number, y: number, r: number, w = 6, s = I, dash = "") =>
  `<circle cx="${n(x)}" cy="${n(y)}" r="${n(r)}" fill="none" stroke="${s}" stroke-width="${w}"${dash ? ` stroke-dasharray="${dash}"` : ""}/>`;
const el = (x: number, y: number, rx: number, ry: number, f = I, rot = 0) =>
  `<ellipse cx="${n(x)}" cy="${n(y)}" rx="${n(rx)}" ry="${n(ry)}" fill="${f}"${rot ? ` transform="rotate(${n(rot)} ${n(x)} ${n(y)})"` : ""}/>`;
const rc = (x: number, y: number, w: number, h: number, r = 0, f = I) =>
  `<rect x="${n(x)}" y="${n(y)}" width="${n(w)}" height="${n(h)}" rx="${n(r)}" fill="${f}"/>`;
const p = (d: string, f = I) => `<path d="${d}" fill="${f}"/>`;
const s = (d: string, w = 6, col = I, dash = "") =>
  `<path d="${d}" fill="none" stroke="${col}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"${dash ? ` stroke-dasharray="${dash}"` : ""}/>`;
const g = (transform: string, body: string) => `<g transform="${transform}">${body}</g>`;

/** Points on a circle, for rays and petals. */
const around = (k: number, phase = 0) =>
  Array.from({ length: k }, (_, i) => phase + (i / k) * Math.PI * 2);

