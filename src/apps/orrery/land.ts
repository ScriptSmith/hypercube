export const LAND_W = 360;
export const LAND_H = 180;

/** The grid as 0 (sea) and 1 (land), row by row from the north. */
export const decodeLand = (rle: string = LAND_RLE): Uint8Array => {
  const out = new Uint8Array(LAND_W * LAND_H);
  rle.split("|").forEach((row, r) => {
    if (r >= LAND_H) return;
    let c = 0;
    let land = 0;
    for (const run of row.split(".")) {
      const n = Number.parseInt(run, 36);
      if (land) out.fill(1, r * LAND_W + c, r * LAND_W + Math.min(LAND_W, c + n));
      c += n;
      land ^= 1;
    }
  });
  return out;
};

/** Land (true) or sea at a latitude and longitude, degrees. */
export const isLand = (grid: Uint8Array, lat: number, lon: number): boolean => {
  const r = Math.max(0, Math.min(LAND_H - 1, Math.floor(90 - lat)));
  const c = ((Math.floor(lon + 180) % LAND_W) + LAND_W) % LAND_W;
  return grid[r * LAND_W + c] === 1;
};
