export type PictureId = keyof typeof PICTURES;

export const PICTURE_IDS = Object.keys(PICTURES) as PictureId[];

const cache = new Map<string, string>();

/** The picture's SVG body (no outer element), drawn on a 100 x 100 grid. */
export const pictureBody = (id: PictureId): string => {
  let body = cache.get(id);
  if (body === undefined) {
    body = PICTURES[id]();
    cache.set(id, body);
  }
  return body;
};

/** A complete SVG element for a picture, sized to fill its box. */
export const pictureSvg = (id: PictureId): string =>
  `<svg viewBox="0 0 100 100" width="100%" height="100%" aria-hidden="true">${pictureBody(id)}</svg>`;

